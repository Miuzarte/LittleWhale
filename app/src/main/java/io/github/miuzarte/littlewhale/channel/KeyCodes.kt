package io.github.miuzarte.littlewhale.channel

import android.view.KeyEvent

/**
 * The key names Android has, and what they mean
 *
 * A caller names a key instead of numbering one, and on a phone that difference matters: the
 * numbers are not memorable, and the half-remembered ones are the dangerous kind - keycode 5 is a
 * call, 26 is the power key, 27 is the camera. A name this table does not have is refused; a number
 * that is wrong is simply a different key, and the screen finds out afterwards
 *
 * The names are the platform's own, taken from `android/keycodes.h` (see
 * `tools/gen-keycodes.mjs`), so `BACK`, `KEYCODE_BACK` and `keycode_back` are one key and mean
 * exactly what the device means by it
 */
object KeyCodes {

    /**
     * The key a caller named, or null when Android has no key by that name
     *
     * A number is read as a keycode and checked against the same table, so a caller that remembers
     * `4` gets the key that really is 4, and one that remembers `45` gets nothing instead of
     * whatever 45 happens to be
     */
    fun resolve(text: String): Int? {
        val asked = text.trim()
        if (asked.isEmpty()) return null
        asked.toIntOrNull()?.let { return if (it in CODES) it else null }
        val bare = asked.uppercase()
            .removePrefix("AKEYCODE_")
            .removePrefix("KEYCODE_")
            .replace('-', '_')
            .replace(' ', '_')
        return BY_NAME[bare]
    }

    /** Whether this is a code the platform defines, which is the only kind worth injecting */
    fun known(code: Int): Boolean = code in CODES

    /**
     * What the platform calls a code, which is also the name this table files it under
     *
     * The prefix is dropped so an answer reads the way a caller would write it, and a code the
     * platform has no name for comes back as the number rather than as a guess
     */
    fun nameOf(code: Int): String {
        val said = KeyEvent.keyCodeToString(code).removePrefix("KEYCODE_")
        return if (said.startsWith("UNKNOWN")) code.toString() else said
    }

