    /**
     * The table as name and code, read once
     *
     * The entries are wrapped across lines to stay readable beside the header they come from, so
     * what separates them is whitespace rather than a line break
     */
    private val BY_NAME: Map<String, Int> = TABLE.trimIndent().splitToSequence(' ', '\t', '\n', '\r')
        .mapNotNull { entry ->
            val split = entry.indexOf('=')
            val code = if (split <= 0) null else entry.substring(split + 1).toIntOrNull()
            if (code == null) null else entry.take(split) to code
        }
        .toMap()

    /** Every code the platform defines, for a caller that named a number instead */
