     * HOME sent to a virtual screen left that display asleep with its last picture still being
     * handed out by `screencap`, which is a model reading a frozen frame and believing it. The
     * phone's own screen has all of that and is where these belong
     */
    val WHOLE_SCREEN: Set<Int> = setOf(
        KeyEvent.KEYCODE_HOME,
        KeyEvent.KEYCODE_POWER,
        KeyEvent.KEYCODE_SLEEP,
        KeyEvent.KEYCODE_SOFT_SLEEP,
    )

