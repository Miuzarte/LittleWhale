/**
 * Regenerate the key name table in `channel/KeyCodes.kt` from Android's own list
 *
 * The names have to be the platform's, not a hand-typed subset: a caller that names a key is
 * trusting this table to mean exactly what the device means by that name, and a table kept by hand
 * is one that quietly disagrees with the phone it runs on. The list is read from the header that
 * defines it, and written into the generated region of the Kotlin file
 *
 * usage: node tools/gen-keycodes.mjs [--to <path to KeyCodes.kt>]
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseArgs } from 'node:util'

/** Where the codes are defined, which is the only source this table trusts */
const SOURCE = 'https://android.googlesource.com/platform/frameworks/native/+/master/include/android/keycodes.h'

/** The region of the Kotlin file this rewrites, everything else in it is hand-written */
const START = '// region generated by tools/gen-keycodes.mjs'
const END = '// endregion generated by tools/gen-keycodes.mjs'

/** Roughly how wide one line of the table may get, which only decides where lines break */
const LINE_WIDTH = 96

/** `AKEYCODE_BACK = 4,` and the like, which is the whole grammar of the header */
const ENTRY = /AKEYCODE_([A-Z0-9_]+)\s*=\s*(\d+)/g

const { values } = parseArgs({
  options: {
    to: {
      type: 'string',
      default: 'app/src/main/java/io/github/miuzarte/littlewhale/channel/KeyCodes.kt',
    },
  },
})

/** The header itself: googlesource hands out base64 when asked for text */
async function fetchHeader() {
  const response = await fetch(`${SOURCE}?format=TEXT`)
  if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`)
  return Buffer.from(await response.text(), 'base64').toString('utf8')
}

const header = await fetchHeader()
const entries = new Map()
for (const [, name, code] of header.matchAll(ENTRY)) entries.set(name, Number(code))
if (entries.size < 100) throw new Error(`only ${entries.size} key names were found, the header moved`)

// Sorted by code rather than by name, because reading it beside the header is how it gets checked
const pairs = [...entries.entries()].sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]))
const lines = []
let line = ''
for (const [name, code] of pairs) {
  const entry = `${name}=${code}`
  if (line !== '' && line.length + entry.length + 1 > LINE_WIDTH) {
    lines.push(line)
    line = ''
  }
  line = line === '' ? entry : `${line} ${entry}`
}
if (line !== '') lines.push(line)

const block = [
  START,
  '    private const val TABLE = """',
  ...lines.map((one) => `        ${one}`),
  '    """',
  END,
].join('\n')

const target = resolve(values.to)
const current = readFileSync(target, 'utf8')
const start = current.indexOf(START)
const end = current.indexOf(END)
if (start < 0 || end < 0 || end < start) throw new Error(`${target} has no generated region to rewrite`)
writeFileSync(target, `${current.slice(0, start)}${block}${current.slice(end + END.length)}`)

const newest = pairs.reduce((best, one) => (one[1] > best[1] ? one : best), pairs[0])
console.log(`gen-keycodes: ${pairs.length} key names into ${values.to}`)
console.log(`gen-keycodes: highest code is ${newest[0]}=${newest[1]}`)
